        plt.plot(range(len(self.num_prey_history)), self.num_prey_history, label='Prey')
        plt.title('Number of Fire Hawks and Prey over Iterations')
        plt.xlabel('Iteration')
        plt.ylabel('Number')
        plt.legend()

        plt.tight_layout()
        plt.show()

